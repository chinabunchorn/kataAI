import { useEffect, useRef, useState } from 'react'
import type { FormEvent, KeyboardEvent } from 'react'
import {
  AlertCircle,
  ArrowUp,
  Carrot,
  Check,
  CheckCircle2,
  ChevronDown,
  ChevronUp,
  Clock,
  Code2,
  Copy,
  Cpu,
  Database,
  FileSpreadsheet,
  Layers,
  LoaderCircle,
  Plus,
  RotateCcw,
  Table,
  Terminal,
  X,
} from 'lucide-react'
import { inspectCsv } from './lib/csv'
import type { CsvDataset } from './lib/csv'
import { validateQuestion } from './lib/submission'

const SAMPLE_CSV_CONTENT = `product,month,units
Notebook,October,120
Notebook,November,80
Pen,October,50
Pen,November,45
`

const DEFAULT_SAMPLE_FILE = new File([SAMPLE_CSV_CONTENT], 'sales_q4.csv', {
  type: 'text/csv',
})

const DEFAULT_GENERATED_PYTHON_CODE = `# Generated by llama.cpp (Local) based on CSV schema
import csv
import json

INPUT_PATH = '/inputs/data.csv'
OUTPUT_PATH = '/outputs/result.json'

october_sales = {}
november_sales = {}

with open(INPUT_PATH, mode='r', encoding='utf-8') as f:
    reader = csv.DictReader(f)
    for row in reader:
        product = row['product']
        month = row['month']
        units = int(row['units'])
        if month == 'October':
            october_sales[product] = units
        elif month == 'November':
            november_sales[product] = units

largest_drop = 0
dropped_product = None

for product, oct_units in october_sales.items():
    nov_units = november_sales.get(product, 0)
    drop = oct_units - nov_units
    if drop > largest_drop:
        largest_drop = drop
        dropped_product = product

result = {
    "product": dropped_product,
    "october_units": october_sales.get(dropped_product, 0),
    "november_units": november_sales.get(dropped_product, 0),
    "change_units": -largest_drop
}

with open(OUTPUT_PATH, mode='w', encoding='utf-8') as f:
    json.dump(result, f, indent=2)
`

type PipelineStep = {
  id: number
  title: string
  subtitle: string
  component: string
  status: 'pending' | 'running' | 'completed' | 'failed'
  durationMs?: number
  details?: Record<string, string>
}

type ChatMessage = {
  id: string
  sender: 'user' | 'assistant'
  question: string
  dataset?: CsvDataset
  timestamp: string
  pipeline?: {
    steps: PipelineStep[]
    isComplete: boolean
    activeStepIndex: number
    totalDurationMs: number
  }
  result?: {
    answer: string
    pythonCode?: string
    json: Record<string, unknown>
    memoryUsage?: string
    telemetry: {
      runtime: string
      guestKernel: string
      networkStatus: string
      jobUid: string
    }
  }
}

const INITIAL_PIPELINE_STEPS: PipelineStep[] = [
  {
    id: 1,
    title: 'Code Generation',
    subtitle: 'Generating Python script based on CSV column schema',
    component: 'llama.cpp (Local)',
    status: 'pending',
  },
  {
    id: 2,
    title: 'Policy & Tool Validation',
    subtitle: 'Validating tool contract, dataset binding and limits',
    component: 'FastAPI Coordinator',
    status: 'pending',
  },
  {
    id: 3,
    title: 'Kubernetes Kata Job Provisioning',
    subtitle: 'Dispatching disposable Pod with RuntimeClass: kata-qemu',
    component: 'OpenStack K8s API',
    status: 'pending',
  },
  {
    id: 4,
    title: 'MicroVM Sandboxed Execution',
    subtitle: 'Executing Python inside isolated guest kernel without network',
    component: 'Kata Containers VM',
    status: 'pending',
  },
  {
    id: 5,
    title: 'Result Extraction & Summarization',
    subtitle: 'Collecting validated JSON and generating natural explanation',
    component: 'llama.cpp (Summarizer)',
    status: 'pending',
  },
]

export default function App() {
  const [messages, setMessages] = useState<ChatMessage[]>([])
  const [inputText, setInputText] = useState('')
  const [selectedFile, setSelectedFile] = useState<File | null>(null)
  const [dataset, setDataset] = useState<CsvDataset | null>(null)
  const [csvError, setCsvError] = useState<string | null>(null)
  const [isProcessingCsv, setIsProcessingCsv] = useState(false)
  const [isSending, setIsSending] = useState(false)
  const [showCsvPreviewModal, setShowCsvPreviewModal] = useState(false)
  const [copiedKey, setCopiedKey] = useState<string | null>(null)
  const [expandedPipelineMsgId, setExpandedPipelineMsgId] = useState<string | null>(null)

  const fileInputRef = useRef<HTMLInputElement>(null)
  const textareaRef = useRef<HTMLTextAreaElement>(null)
  const chatBottomRef = useRef<HTMLDivElement>(null)

  // Scroll to bottom when new messages arrive or pipeline updates
  useEffect(() => {
    chatBottomRef.current?.scrollIntoView?.({ behavior: 'smooth' })
  }, [messages])

  // Process CSV file whenever selectedFile changes
  useEffect(() => {
    if (!selectedFile) {
      setDataset(null)
      setCsvError(null)
      return
    }

    let isSubscribed = true
    setIsProcessingCsv(true)
    setCsvError(null)

    inspectCsv(selectedFile)
      .then((parsed) => {
        if (isSubscribed) {
          setDataset(parsed)
          setIsProcessingCsv(false)
        }
      })
      .catch((err: Error) => {
        if (isSubscribed) {
          setCsvError(err.message)
          setDataset(null)
          setIsProcessingCsv(false)
        }
      })

    return () => {
      isSubscribed = false
    }
  }, [selectedFile])

  function handleFileSelect(event: React.ChangeEvent<HTMLInputElement>) {
    const file = event.target.files?.[0]
    if (file) {
      setSelectedFile(file)
    }
  }

  function handleRemoveFile() {
    setSelectedFile(null)
    setDataset(null)
    setCsvError(null)
    if (fileInputRef.current) {
      fileInputRef.current.value = ''
    }
  }

  function handleUseSampleCsv() {
    setSelectedFile(DEFAULT_SAMPLE_FILE)
  }


  function handleResetChat() {
    setMessages([])
    setInputText('')
    handleRemoveFile()
  }

  async function handleSendMessage(event?: FormEvent) {
    if (event) event.preventDefault()
    if (isSending) return

    const validation = validateQuestion(inputText)
    if (validation) {
      alert(validation)
      return
    }

    const currentQuestion = inputText.trim()
    const currentDataset = dataset ?? undefined
    const messageId = `msg-${Date.now()}`

    // 1. Add User Message
    const userMessage: ChatMessage = {
      id: messageId,
      sender: 'user',
      question: currentQuestion,
      dataset: currentDataset,
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    }

    // 2. Prepare Assistant Message with Initial Pipeline
    const assistantMsgId = `assistant-${Date.now()}`
    const assistantMessage: ChatMessage = {
      id: assistantMsgId,
      sender: 'assistant',
      question: currentQuestion,
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      pipeline: {
        steps: INITIAL_PIPELINE_STEPS.map((s) => ({ ...s })),
        isComplete: false,
        activeStepIndex: 0,
        totalDurationMs: 0,
      },
    }

    setMessages((prev) => [...prev, userMessage, assistantMessage])
    setExpandedPipelineMsgId(assistantMsgId)
    setInputText('')
    setIsSending(true)

    // Simulate the 5-step background execution progression
    const stepDurations = [450, 300, 600, 500, 400]
    let accumulatedMs = 0

    for (let i = 0; i < 5; i++) {
      // Mark current step as running
      setMessages((prev) =>
        prev.map((msg) => {
          if (msg.id !== assistantMsgId || !msg.pipeline) return msg
          const newSteps = [...msg.pipeline.steps]
          newSteps[i] = { ...newSteps[i], status: 'running' }
          return {
            ...msg,
            pipeline: {
              ...msg.pipeline,
              steps: newSteps,
              activeStepIndex: i,
            },
          }
        }),
      )

      await new Promise((r) => setTimeout(r, stepDurations[i]))
      accumulatedMs += stepDurations[i]

      // Mark current step as completed
      setMessages((prev) =>
        prev.map((msg) => {
          if (msg.id !== assistantMsgId || !msg.pipeline) return msg
          const newSteps = [...msg.pipeline.steps]
          newSteps[i] = {
            ...newSteps[i],
            status: 'completed',
            durationMs: stepDurations[i],
          }
          return {
            ...msg,
            pipeline: {
              ...msg.pipeline,
              steps: newSteps,
              activeStepIndex: i + 1,
              totalDurationMs: accumulatedMs,
            },
          }
        }),
      )
    }

    // Pipeline finished -> append final calculated answer and JSON result
    setMessages((prev) =>
      prev.map((msg) => {
        if (msg.id !== assistantMsgId || !msg.pipeline) return msg
        return {
          ...msg,
          pipeline: {
            ...msg.pipeline,
            isComplete: true,
          },
          result: {
            answer:
              'Notebook sales dropped the most between October and November, falling from 120 units to 80 units (an absolute drop of 40 units). Pen sales had a smaller decrease of 5 units.',
            pythonCode: DEFAULT_GENERATED_PYTHON_CODE,
            json: {
              product: 'Notebook',
              october_units: 120,
              november_units: 80,
              change_units: -40,
            },
            memoryUsage: '42 MB',
            telemetry: {
              runtime: 'kata-qemu (MicroVM)',
              guestKernel: '6.1.102-kata',
              networkStatus: 'Egress Denied (Default-Deny CNI)',
              jobUid: `job-kata-${Math.random().toString(36).substring(2, 9)}`,
            },
          },
        }
      }),
    )

    setIsSending(false)
  }

  function handleKeyDown(event: KeyboardEvent<HTMLTextAreaElement>) {
    if (event.key === 'Enter' && !event.shiftKey) {
      event.preventDefault()
      handleSendMessage()
    }
  }

  function handleCopyText(text: string, key: string) {
    navigator.clipboard.writeText(text)
    setCopiedKey(key)
    setTimeout(() => setCopiedKey(null), 2000)
  }

  const inputForm = (
    <form className="gemini-input-card" onSubmit={handleSendMessage}>
      {/* Attached CSV Chip inside the pill */}
      {selectedFile && (
        <div className="input-file-chip">
          <FileSpreadsheet size={16} className="file-chip-icon" />
          <div className="file-chip-info">
            <span className="file-chip-name">{selectedFile.name}</span>
            {dataset && (
              <span className="file-chip-details">
                ({dataset.rowCount} rows • {dataset.headers.length} cols)
              </span>
            )}
          </div>
          <button
            type="button"
            className="file-chip-remove"
            onClick={handleRemoveFile}
            title="Remove file"
          >
            <X size={14} />
          </button>
        </div>
      )}

      {csvError && (
        <div className="input-error-banner">
          <AlertCircle size={14} />
          <span>{csvError}</span>
        </div>
      )}

      <div className="input-row">
        {/* CSV File Input Button (Plus Icon like Gemini) */}
        <input
          ref={fileInputRef}
          type="file"
          accept=".csv"
          style={{ display: 'none' }}
          onChange={handleFileSelect}
        />

        <button
          type="button"
          className="attach-btn"
          onClick={() => fileInputRef.current?.click()}
          title="Attach CSV file"
          disabled={isProcessingCsv}
        >
          <Plus size={20} />
        </button>

        {/* Prompt Textarea */}
        <textarea
          ref={textareaRef}
          rows={1}
          className="gemini-textarea"
          placeholder={
            selectedFile
              ? 'Ask a question about this CSV...'
              : 'Attach a CSV file and ask a question...'
          }
          value={inputText}
          onChange={(e) => setInputText(e.target.value)}
          onKeyDown={handleKeyDown}
        />

        {/* Send Button */}
        <button
          type="submit"
          className={`send-btn ${inputText.trim() ? 'active' : ''}`}
          disabled={!inputText.trim() || isSending || isProcessingCsv}
          title="Send question"
        >
          {isSending ? <LoaderCircle size={18} className="spinning" /> : <ArrowUp size={20} />}
        </button>
      </div>
    </form>
  )

  return (
    <div className="gemini-app">
      {/* Top Navigation Bar */}
      <header className="gemini-header">
        <div className="header-left">
          <div className="brand-badge">
            <span className="brand-logo">KataAI</span>
          </div>
        </div>

        <div className="header-actions">
          {selectedFile ? (
            <button
              type="button"
              className="action-pill-btn"
              onClick={() => setShowCsvPreviewModal(true)}
              title="Preview attached CSV"
            >
              <Table size={14} />
              <span>Preview CSV</span>
            </button>
          ) : (
            <button
              type="button"
              className="action-pill-btn"
              onClick={handleUseSampleCsv}
              title="Load sample sales data"
            >
              <Database size={14} />
              <span>Use Sample Data</span>
            </button>
          )}

          <button
            type="button"
            className="action-icon-btn"
            onClick={handleResetChat}
            title="Start new analysis"
          >
            <RotateCcw size={16} />
          </button>
        </div>
      </header>

      {/* Main Chat Content Area */}
      <main className="gemini-main">
        {messages.length === 0 ? (
          /* Empty State - Gemini Welcome Screen */
          <div className="gemini-hero">
            <div className="hero-sparkle">
              <Carrot size={38} className="sparkle-icon" />
            </div>

            <h1 className="hero-greeting">What do you want to know?</h1>
            <p className="hero-subtext">
              Ask any question about your dataset. We will test and run the generated Python code inside an isolated{' '}
              <strong>Kata Container</strong> to ensure complete safety and isolation.
            </p>

            <div className="hero-input-wrapper">
              {inputForm}
            </div>
          </div>
        ) : (
          /* Active Chat Stream */
          <div className="chat-stream">
            {messages.map((msg, index) => (
              <div key={msg.id} className={`chat-row ${msg.sender}`}>
                {msg.sender === 'user' ? (
                  <div className="user-message-container">
                    {msg.dataset && (
                      <div className="attached-dataset-badge">
                        <FileSpreadsheet size={15} />
                        <span className="dataset-name">{msg.dataset.file.name}</span>
                        <span className="dataset-meta">
                          {msg.dataset.rowCount} rows • {msg.dataset.headers.length} cols
                        </span>
                      </div>
                    )}
                    <div className="user-bubble">{msg.question}</div>
                  </div>
                ) : (
                  <div className="assistant-message-container">
                    <div className="assistant-avatar">
                      <Carrot size={18} />
                    </div>

                    <div className="assistant-content">
                      {/* 4-5 Pipeline Statuses (Accordion) */}
                      {msg.pipeline && (
                        <div className="pipeline-container">
                          <button
                            type="button"
                            className="pipeline-header"
                            onClick={() =>
                              setExpandedPipelineMsgId((prev) =>
                                prev === msg.id ? null : msg.id,
                              )
                            }
                          >
                            <div className="pipeline-title-group">
                              <Layers size={16} className="pipeline-icon" />
                              <span className="pipeline-title">
                                {msg.pipeline.isComplete
                                  ? 'Sandboxed Execution Complete'
                                  : `Running Sandbox Pipeline (${msg.pipeline.activeStepIndex + 1}/5)...`}
                              </span>
                              <span className="duration-tag">
                                {msg.pipeline.totalDurationMs > 0
                                  ? `${(msg.pipeline.totalDurationMs / 1000).toFixed(2)}s`
                                  : 'in progress'}
                              </span>
                            </div>

                            <div className="pipeline-toggle">
                              {expandedPipelineMsgId === msg.id ? (
                                <ChevronUp size={16} />
                              ) : (
                                <ChevronDown size={16} />
                              )}
                            </div>
                          </button>

                          {expandedPipelineMsgId === msg.id && (
                            <div className="pipeline-steps-list">
                              {msg.pipeline.steps.map((step) => (
                                <div key={step.id} className={`step-item ${step.status}`}>
                                  <div className="step-indicator">
                                    {step.status === 'completed' && (
                                      <CheckCircle2 size={16} className="step-icon done" />
                                    )}
                                    {step.status === 'running' && (
                                      <LoaderCircle size={16} className="step-icon spinning" />
                                    )}
                                    {step.status === 'pending' && <span className="step-dot" />}
                                  </div>

                                  <div className="step-info">
                                    <div className="step-main">
                                      <span className="step-name">{step.title}</span>
                                      <span className="step-component">[{step.component}]</span>
                                    </div>
                                    <div className="step-sub">{step.subtitle}</div>
                                  </div>

                                  {step.durationMs && (
                                    <div className="step-time">
                                      {(step.durationMs / 1000).toFixed(2)}s
                                    </div>
                                  )}
                                </div>
                              ))}
                            </div>
                          )}
                        </div>
                      )}

                      {/* Natural Language Result & JSON Payload */}
                      {msg.result && (
                        <div className="result-card">
                          <div className="result-answer">{msg.result.answer}</div>

                          {/* Generated Python Code Box */}
                          <div className="json-box">
                            <div className="json-header">
                              <div className="json-title-group">
                                <div className="json-title">
                                  <Code2 size={14} />
                                  <span>Generated Python Code</span>
                                </div>
                                <span className="json-runtime-tag">
                                  <Cpu size={12} />
                                  <span>llama.cpp (Local)</span>
                                </span>
                              </div>
                              <button
                                type="button"
                                className="copy-json-btn"
                                onClick={() =>
                                  handleCopyText(
                                    msg.result!.pythonCode || DEFAULT_GENERATED_PYTHON_CODE,
                                    `python-${index}`,
                                  )
                                }
                              >
                                {copiedKey === `python-${index}` ? (
                                  <>
                                    <Check size={13} />
                                    <span>Copied</span>
                                  </>
                                ) : (
                                  <>
                                    <Copy size={13} />
                                    <span>Copy Code</span>
                                  </>
                                )}
                              </button>
                            </div>
                            <pre className="json-code">
                              {msg.result.pythonCode || DEFAULT_GENERATED_PYTHON_CODE}
                            </pre>
                          </div>

                          {/* Validated JSON Output Box */}
                          <div className="json-box">
                            <div className="json-header">
                              <div className="json-title-group">
                                <div className="json-title">
                                  <Terminal size={14} />
                                  <span>Validated JSON Output</span>
                                </div>
                                <span className="json-runtime-tag">
                                  <Clock size={12} />
                                  <span>
                                    Runtime:{' '}
                                    {(
                                      (msg.pipeline?.steps[3]?.durationMs ?? 500) / 1000
                                    ).toFixed(2)}
                                    s
                                  </span>
                                </span>
                                <span className="json-runtime-tag">
                                  <Cpu size={12} />
                                  <span>Memory: {msg.result.memoryUsage ?? '42 MB'}</span>
                                </span>
                              </div>
                              <button
                                type="button"
                                className="copy-json-btn"
                                onClick={() =>
                                  handleCopyText(
                                    JSON.stringify(msg.result!.json, null, 2),
                                    `json-${index}`,
                                  )
                                }
                              >
                                {copiedKey === `json-${index}` ? (
                                  <>
                                    <Check size={13} />
                                    <span>Copied</span>
                                  </>
                                ) : (
                                  <>
                                    <Copy size={13} />
                                    <span>Copy JSON</span>
                                  </>
                                )}
                              </button>
                            </div>
                            <pre className="json-code">
                              {JSON.stringify(msg.result.json, null, 2)}
                            </pre>
                          </div>
                        </div>
                      )}
                    </div>
                  </div>
                )}
              </div>
            ))}
            <div ref={chatBottomRef} />
          </div>
        )}
      </main>

      {/* Floating Gemini-Style Input Pill at Bottom when in chat */}
      {messages.length > 0 && (
        <footer className="gemini-footer">
          {inputForm}
        </footer>
      )}

      {/* CSV Data Preview Modal */}
      {showCsvPreviewModal && dataset && (
        <div className="modal-backdrop" onClick={() => setShowCsvPreviewModal(false)}>
          <div className="modal-content" onClick={(e) => e.stopPropagation()}>
            <div className="modal-header">
              <div className="modal-title-group">
                <FileSpreadsheet size={20} />
                <h3>{dataset.file.name} (Data Preview)</h3>
              </div>
              <button
                type="button"
                className="modal-close-btn"
                onClick={() => setShowCsvPreviewModal(false)}
              >
                <X size={18} />
              </button>
            </div>

            <div className="modal-body">
              <p className="preview-note">
                Showing first {dataset.preview.length} rows out of {dataset.rowCount} rows.
              </p>
              <div className="table-wrapper">
                <table className="preview-table">
                  <thead>
                    <tr>
                      {dataset.headers.map((h, i) => (
                        <th key={i}>{h}</th>
                      ))}
                    </tr>
                  </thead>
                  <tbody>
                    {dataset.preview.map((row, rIndex) => (
                      <tr key={rIndex}>
                        {row.map((cell, cIndex) => (
                          <td key={cIndex}>{cell}</td>
                        ))}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}
